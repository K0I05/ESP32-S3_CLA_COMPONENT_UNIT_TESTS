def solve_ellipsoid_coefficients(samples):
    """
    Solves for the 9 ellipsoid coefficients from calibration sample data.
    
    The ellipsoid equation is:
    Ax^2 + By^2 + Cz^2 + Dxy + Exz + Fyz + Gx + Hy + Iz = 1
    
    Args:
        samples: Nx3 array of [x, y, z] points
    
    Returns:
        Array of 9 coefficients [A, B, C, D, E, F, G, H, I]
    """
    n = len(samples)
    
    # Build the design matrix
    # Each row is [x^2, y^2, z^2, xy, xz, yz, x, y, z]
    D = np.zeros((n, 9))
    for i, (x, y, z) in enumerate(samples):
        D[i] = [x*x, y*y, z*z, x*y, x*z, y*z, x, y, z]
    
    # Right-hand side (all ones)
    b = np.ones(n)
    
    # Solve the least squares problem: D @ coeffs = b
    # coeffs = (D^T @ D)^(-1) @ D^T @ b
    coeffs, residuals, rank, s = np.linalg.lstsq(D, b, rcond=None)
    
    return coeffs

